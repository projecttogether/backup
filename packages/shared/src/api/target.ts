import { z } from "zod";
import { secretInput, timeOfDaySchema } from "./common";

/*
 * The target: one restic repository in an S3-compatible bucket (Hetzner
 * Object Storage, AWS S3, Backblaze B2, Scaleway, MinIO, …). Every source
 * writes into it, each with its own tag. The repository password encrypts
 * everything; with the S3 keys it is the recovery kit.
 */

/** The address of an S3-compatible storage, e.g. https://fsn1.your-objectstorage.com */
export const s3EndpointSchema = z.url({
  protocol: /^https?$/,
  message: "Enter the endpoint's URL, e.g. https://fsn1.your-objectstorage.com",
});
/** e.g. fsn1; some providers need it for signing. */
export const s3RegionSchema = z.string().trim().max(64).default("");
export const s3BucketSchema = z
  .string()
  .trim()
  .regex(
    /^[a-z0-9][a-z0-9.-]{1,61}[a-z0-9]$/,
    "Enter the bucket's name (lowercase letters, digits, dots, hyphens)",
  );
/** A folder inside the bucket; empty: the bucket's root. */
export const s3PrefixSchema = z
  .string()
  .trim()
  .max(200)
  .regex(
    /^([A-Za-z0-9._-]+(\/[A-Za-z0-9._-]+)*)?$/,
    "Letters, digits, dots, hyphens and slashes between them",
  )
  .default("");
export const s3AccessKeyIdSchema = z.string().trim().min(1, "Enter the access key").max(200);

export const targetInputSchema = z.object({
  endpoint: s3EndpointSchema,
  region: s3RegionSchema,
  bucket: s3BucketSchema,
  prefix: s3PrefixSchema,
  accessKeyId: s3AccessKeyIdSchema,
  secretAccessKey: secretInput(500),
});
export type TargetInput = z.input<typeof targetInputSchema>;

/**
 * missing: no repository at this location yet; ready: the password opens
 * it; wrong_password: a repository is there, but this password does not
 * open it; error: the bucket cannot be reached (message says why).
 */
export const repositoryStateSchema = z.enum(["unknown", "missing", "ready", "wrong_password", "error"]);
export type RepositoryState = z.infer<typeof repositoryStateSchema>;

/** What the bucket's settings protect, read with the S3 API; null where the provider does not say. */
export const bucketProtectionSchema = z.object({
  checkedAt: z.string(),
  versioning: z.enum(["enabled", "suspended", "off"]).nullable(),
  objectLock: z
    .object({
      enabled: z.boolean(),
      mode: z.enum(["GOVERNANCE", "COMPLIANCE"]).nullable(),
      days: z.number().nullable(),
    })
    .nullable(),
  /** Lifecycle rules that clean up after restic deletes: old versions, delete markers, uploads. */
  lifecycle: z
    .object({
      noncurrentDays: z.number().nullable(),
      expiredDeleteMarkers: z.boolean(),
      abortMultipartDays: z.number().nullable(),
    })
    .nullable(),
  /** Why a setting could not be read, e.g. "Access denied". */
  error: z.string().nullable(),
});
export type BucketProtection = z.infer<typeof bucketProtectionSchema>;

export const repositoryStatsSchema = z.object({
  checkedAt: z.string(),
  /** Bytes stored in the bucket (after deduplication and compression). */
  storedBytes: z.number().nullable(),
  snapshots: z.number().nullable(),
});

export const integrityCheckSchema = z.object({
  at: z.string(),
  ok: z.boolean(),
  /** Share of the data that was read and verified, e.g. "5%"; null: structure only. */
  readData: z.string().nullable(),
  message: z.string().nullable(),
});

export const targetSchema = z.object({
  configured: z.boolean(),
  endpoint: z.string().nullable(),
  region: z.string(),
  bucket: z.string().nullable(),
  prefix: z.string(),
  accessKeyId: z.string().nullable(),
  secretAccessKeyHint: z.string().nullable(),
  /** The restic repository address, e.g. s3:https://fsn1.your-objectstorage.com/bucket/prefix */
  repositoryUrl: z.string().nullable(),
  repository: z.object({
    state: repositoryStateSchema,
    message: z.string().nullable(),
    checkedAt: z.string().nullable(),
    /** A repository password is stored (generated by the app or entered for an existing repository). */
    hasPassword: z.boolean(),
  }),
  /** When an admin confirmed storing the recovery kit; reset when the target moves. */
  recoveryKitConfirmedAt: z.string().nullable(),
  protection: bucketProtectionSchema.nullable(),
  stats: repositoryStatsSchema.nullable(),
  lastCheck: integrityCheckSchema.nullable(),
  /** Daily upkeep (retention, prune, integrity check, this app's own database), server time. */
  maintenanceTime: timeOfDaySchema,
  timezone: z.string(),
});
export type Target = z.infer<typeof targetSchema>;

/** POST /target/connect: use an existing repository with its password. */
export const targetConnectSchema = z.object({ password: z.string().min(1, "Enter the password").max(500) });

export const maintenanceInputSchema = z.object({ maintenanceTime: timeOfDaySchema });
